import { Stack, Validations } from 'aws-cdk-lib';
import { IConstruct } from 'constructs';
import * as lambda from 'aws-cdk-lib/aws-lambda';
import * as cr from 'aws-cdk-lib/custom-resources';
import { config } from './config';
import { buildApp } from './app';

/**
 * cdk-nag (AwsSolutions) findings that are accepted for this sample, each with its reason.
 * Acknowledgements name exact finding IDs, so any NEW wildcard or rule violation still
 * fails the synth.
 */
function ack(scope: IConstruct, reason: string, ...ids: string[]) {
  for (const id of ids) Validations.of(scope).acknowledge({ id, reason });
}

/** The CDK Provider framework invokes handler versions ("<fn>.Arn:*"); generated by aws-cdk-lib. */
function ackProviderFrameworks(stack: Stack) {
  const fnIds = stack.node.findAll()
    .filter((c): c is lambda.CfnFunction => c instanceof lambda.CfnFunction)
    .map((f) => stack.getLogicalId(f));
  for (const p of stack.node.findAll().filter((c) => c instanceof cr.Provider)) {
    ack(p, 'CDK Provider framework (aws-cdk-lib): may invoke any version of its own handler functions.',
      ...fnIds.map((id) => `AwsSolutions-IAM5[Resource::<${id}.Arn>:*]`));
    ack(p, 'CDK Provider framework waiter state machine (aws-cdk-lib); short-lived, no business data.',
      'AwsSolutions-SF1', 'AwsSolutions-SF2');
  }
}

export function applyNagSuppressions(s: ReturnType<typeof buildApp>) {
  const { region, account } = s.network;
  const lambdaBasic = 'AwsSolutions-IAM4[Policy::arn:<AWS::Partition>:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole]';
  const instances = `AwsSolutions-IAM5[Resource::arn:aws:ec2:${region}:${account}:instance/*]`;
  const apObjects = `AwsSolutions-IAM5[Resource::arn:aws:s3:${region}:${account}:accesspoint/${config.accessPoint.name}/object/*]`;

  for (const stack of [s.directory, s.fsx]) {
    ack(stack, 'Demo passwords are generated once and not rotated: rotating them also requires updating '
      + 'AD and the SVM stored credential, which the sample does not implement (see README, "Credentials").',
    'AwsSolutions-SMG4');
  }

  ack(s.client, 'AWS managed policy is the documented minimum for SSM Run Command / Session Manager on the hosts.',
    'AwsSolutions-IAM4[Policy::arn:<AWS::Partition>:iam::aws:policy/AmazonSSMManagedInstanceCore]');
  ack(s.client, 'Secrets Manager appends a random 6-character suffix to secret ARNs; the name is fixed.',
    `AwsSolutions-IAM5[Resource::arn:aws:secretsmanager:${region}:${account}:secret:${config.prefix}/vsadmin-*]`);
  ack(s.client, 'Demo hosts: basic 5-minute monitoring is sufficient.', 'AwsSolutions-EC28');
  ack(s.client, 'Demo hosts must be removable by stack deletion; no data lives on them.', 'AwsSolutions-EC29');

  for (const stack of [s.identity, s.sftp, s.demo]) {
    ack(stack, 'AWS managed policy grants only CloudWatch Logs writes for the function.', lambdaBasic);
    ackProviderFrameworks(stack);
  }
  for (const stack of [s.identity, s.sftp]) {
    ack(stack, 'ssm:DescribeInstanceInformation, ssm:GetCommandInvocation, ec2:DescribeInstances and '
      + 'fsx:DescribeStorageVirtualMachines (and ds:DescribeDirectories, used by transfer:CreateAccess to '
      + 'validate the AD group) do not support resource-level permissions.', 'AwsSolutions-IAM5[Resource::*]');
    ack(stack, 'Start/stop/send-command are conditioned on the admin host Name tag; instance IDs are not '
      + 'known at synth time (hosts are looked up through SSM parameters).', instances);
  }
  ack(s.sftp, 'Transfer data roles: object access on the one access point; the folder is narrowed by the '
    + 'per-group session policy and the access-point policy.', apObjects);
  ack(s.sftp.node.findChild('AuditAccessLogBucket'), 'Server access log destination for the audit bucket; '
    + 'a log bucket cannot log to itself without an endless loop.', 'AwsSolutions-S1');

  ack(s.demo, 'Self-test discovery (transfer:ListServers, fsx:Describe*, ec2:DescribeVpcEndpoints, '
    + 'ssm:GetCommandInvocation) has no resource-level permissions; all read-only.', 'AwsSolutions-IAM5[Resource::*]');
  ack(s.demo, 'ssm:SendCommand is conditioned on the SFTP client and SMB reader Name tags.', instances);
  ack(s.demo, 'Deliberately allowed: the self-test proves the access-point policy still denies this role.', apObjects);
}
